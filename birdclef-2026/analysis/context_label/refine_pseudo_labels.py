site_cnt.plot.barh(ax=ax)
ax.set_xlabel("# pseudo-labels")
ax.set_title("Pseudo-labels by site")
plt.tight_layout()
plt.savefig(f"{OUT}/pseudo_v2_coverage.png", dpi=110)
plt.close()
print(f"Saved {OUT}/pseudo_v2_coverage.png")


